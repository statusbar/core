auto format_duration(double nanoseconds) -> std::string
{
    if (nanoseconds < 1'000.0) {
        return std::format("{:.2f} ns", nanoseconds);
    }
    if (nanoseconds < 1'000'000.0) {
        return std::format("{:.2f} \xce\xbcs", nanoseconds / 1'000.0);
    }
    if (nanoseconds < 1'000'000'000.0) {
        return std::format("{:.2f} ms", nanoseconds / 1'000'000.0);
    }
    return std::format("{:.2f} s", nanoseconds / 1'000'000'000.0);
}

auto format_timestamp_ns(int64_t nanoseconds) -> std::string
{
    int64_t const ms = nanoseconds / 1'000'000;
    return std::format("[{:3}.{:03}]", ms / 1000, ms % 1000);
}

